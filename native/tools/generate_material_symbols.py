"""Generate native/src/symbols_data.rs from Google's Material Symbols.

Inputs (official sources, Apache License 2.0):
  1. MaterialSymbolsOutlined[FILL,GRAD,opsz,wght].ttf and its .codepoints file
     from github.com/google/material-design-icons/tree/<commit>/variablefont
  2. Icon metadata (tags, categories) from
     https://fonts.google.com/metadata/icons?key=material_symbols&incomplete=true

The variable font is instanced at the WebView launcher's style (FILL 0,
GRAD 0, opsz 24, wght 300) and each glyph becomes an SVG path in the same
24x24 view box as native/ui/icons.slint, so the existing `Icon` component
renders it. Nothing is fetched at runtime.

Usage (run with `python -I`; inputs are data, never imported):
  python -I generate_material_symbols.py <font.ttf> <codepoints> <metadata.json> \
      <source-label> <out.rs>
"""
import json
import sys

from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont

font_path, codepoints_path, metadata_path, source_label, out_path = sys.argv[1:6]

font = TTFont(font_path)
font = instantiateVariableFont(font, {"FILL": 0, "GRAD": 0, "opsz": 24, "wght": 300})
units = font["head"].unitsPerEm
cmap = font.getBestCmap()
glyphs = font.getGlyphSet()

codepoints = {}
with open(codepoints_path, encoding="utf-8") as handle:
    for line in handle:
        name, code = line.split()
        codepoints[name] = int(code, 16)

text = open(metadata_path, encoding="utf-8").read()
metadata = json.loads(text[text.index("{"):])
info = {}
for icon in metadata["icons"]:
    if "Material Symbols Outlined" in icon.get("unsupported_families", []):
        continue
    info[icon["name"]] = icon

# Material Symbols glyphs are drawn in a 0..units em box (y up, baseline at
# 0); the 24 view box is that box flipped: y' = (units - y) * 24 / units.
scale = 24.0 / units


def number(value: float) -> str:
    text = f"{value:.1f}".rstrip("0").rstrip(".")
    return "0" if text in ("-0", "") else text


class CompactPen(SVGPathPen):
    def __init__(self, glyph_set):
        super().__init__(glyph_set, ntos=number)


# Tags carried by many icons ("symbol", "icon", "glyph", ...) add size but
# no search value; keep only distinctive ones.
tag_counts = {}
for icon in info.values():
    for tag in {t.lower().replace(" ", "_") for t in icon.get("tags", [])}:
        tag_counts[tag] = tag_counts.get(tag, 0) + 1
common_tag_limit = max(1, len(info) // 50)

categories = sorted({c for icon in info.values() for c in icon.get("categories", [])})
category_index = {c: i for i, c in enumerate(categories)}

rows = []
for name in sorted(codepoints):
    code = codepoints[name]
    glyph_name = cmap.get(code)
    if glyph_name is None or not all(c.islower() or c.isdigit() or c == "_" for c in name):
        continue
    if not (1 <= len(name) <= 64):
        continue
    pen = CompactPen(glyphs)
    glyphs[glyph_name].draw(TransformPen(pen, (scale, 0, 0, -scale, 0, 24.0)))
    path = pen.getCommands()
    if not path:
        continue
    meta = info.get(name, {})
    tags = " ".join(
        sorted(
            t
            for t in {t.lower().replace(" ", "_") for t in meta.get("tags", [])}
            if t.isascii() and tag_counts.get(t, 0) <= common_tag_limit and t != name
        )
    )
    category = meta.get("categories", ["other"])[0] if meta.get("categories") else None
    rows.append((name, tags, category_index.get(category, 255), int(meta.get("popularity", 0)), path))

with open(out_path, "w", encoding="utf-8", newline="\n") as out:
    out.write("// Generated by native/tools/generate_material_symbols.py. Do not edit.\n")
    out.write("// Google Material Symbols Outlined (Apache License 2.0), instanced at\n")
    out.write("// FILL 0, GRAD 0, opsz 24, wght 300; 24x24 view box paths.\n")
    out.write(f"// Source: {source_label}\n\n")
    out.write(f"pub const SOURCE: &str = {json.dumps(source_label)};\n\n")
    out.write("pub static CATEGORIES: &[&str] = &[\n")
    for c in categories:
        out.write(f"    {json.dumps(c)},\n")
    out.write("];\n\n")
    out.write("/// (name, space-separated tags, category index or 255, popularity, path)\n")
    out.write("pub static SYMBOLS: &[(&str, &str, u8, u32, &str)] = &[\n")
    for name, tags, category, popularity, path in rows:
        out.write(f"    ({json.dumps(name)}, {json.dumps(tags)}, {category}, {popularity}, {json.dumps(path)}),\n")
    out.write("];\n")

print(f"units={units} symbols={len(rows)} categories={len(categories)}")
