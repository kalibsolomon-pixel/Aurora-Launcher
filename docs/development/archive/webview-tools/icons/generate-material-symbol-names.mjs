// Regenerates src/lib/instances/materialSymbolNames.ts from the pinned
// material-symbols package (Google Material Symbols, Apache-2.0). The list is
// presentation data for the instance icon picker; names never reach a path.
import { readFileSync, writeFileSync } from 'node:fs';
const root = new URL('../../', import.meta.url);
const pkg = JSON.parse(readFileSync(new URL('node_modules/material-symbols/package.json', root), 'utf8'));
const types = readFileSync(new URL('node_modules/material-symbols/index.d.ts', root), 'utf8');
// Letter-led names first: the numeric badges ("10k", "2mp") make a poor first page.
const digitLast = (name) => (/^[0-9]/.test(name) ? `~${name}` : name);
const names = [...new Set([...types.matchAll(/"([a-z0-9_]+)"/g)].map(m => m[1]))].sort((a, b) => (digitLast(a) < digitLast(b) ? -1 : digitLast(a) > digitLast(b) ? 1 : 0));
if (names.length < 1000) throw new Error(`unexpectedly few symbols: ${names.length}`);
const body = `// Generated by tools/icons/generate-material-symbol-names.mjs from material-symbols@${pkg.version}.
// Google Material Symbols (Apache-2.0). Do not edit by hand.
export const MATERIAL_SYMBOLS_VERSION = ${JSON.stringify(pkg.version)};
export const materialSymbolNames: readonly string[] = ${JSON.stringify(names)};
`;
writeFileSync(new URL('src/lib/instances/materialSymbolNames.ts', root), body);
console.log(`${names.length} symbols from material-symbols@${pkg.version}`);
