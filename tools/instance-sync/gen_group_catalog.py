"""Generate core/src/instance_sync/group_catalog.rs from docs/instance-sync/CATALOG.md.

Run with `python -I tools/instance-sync/gen_group_catalog.py` from the repository root.
Only rows whose decision begins with "Sync" are emitted; every other key stays local.
"""
import pathlib

ROOT = pathlib.Path(__file__).resolve().parents[2]
lines = (ROOT / "docs/instance-sync/CATALOG.md").read_text(encoding="utf-8").splitlines()
section, vanilla, aurora = "", [], []
for line in lines:
    if line.startswith("## "):
        section = line
    if not line.startswith("| `"):
        continue
    cells = [c.strip() for c in line.strip().strip("|").split("|")]
    name, decision = cells[0].strip("`"), cells[-1]
    if not decision.startswith("Sync"):
        continue
    if "Vanilla per-key" in section or "Enumerated" in section:
        vanilla.append(name)
    elif "Aurora JSON" in section:
        if "activeProfile" == name:
            kind = "ActiveProfile"
        elif "KeyCombo" in decision:
            kind = "KeyCombo"
        elif "modifier mask" in decision:
            kind = "ModifierMask"
        else:
            kind = "Plain"
        aurora.append((name, kind, cells[3] == "Profile"))

out = ["// @generated by tools/instance-sync/gen_group_catalog.py from docs/instance-sync/CATALOG.md.",
       "// Do not edit by hand; keys absent here stay per-instance.",
       "",
       "use super::group::AuroraKind;",
       "",
       f"pub(super) const VANILLA_KEYS: [&str; {len(vanilla)}] = ["]
out += [f'    "{k}",' for k in sorted(set(vanilla))]
out += ["];", "", f"pub(super) const AURORA_FIELDS: [(&str, AuroraKind, bool); {len(aurora)}] = ["]
out += [f'    ("{n}", AuroraKind::{k}, {str(p).lower()}),' for n, k, p in sorted(aurora)]
out += ["];", ""]
assert len(set(vanilla)) == len(vanilla)
(ROOT / "core/src/instance_sync/group_catalog.rs").write_text("\n".join(out), encoding="utf-8", newline="\n")
print(len(vanilla), "vanilla keys,", len(aurora), "aurora fields")
