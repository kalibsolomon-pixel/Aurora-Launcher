import {readFile,writeFile} from 'node:fs/promises';
import {execFileSync} from 'node:child_process';
import {createHash} from 'node:crypto';
import assert from 'node:assert/strict';
const git=(...args)=>execFileSync('git',args,{encoding:'utf8'}).trim();
const baseline=JSON.parse(await readFile('docs/ui-3-1/baseline.json','utf8'));
const scoped=['src/lib/instances/ModrinthBrowse.svelte','tools/visual/ui3.test.mjs','tools/visual/l1.test.mjs'];
for(const item of [...baseline.tracked,...baseline.protected])if(!scoped.includes(item.path))assert.equal(createHash('sha256').update(await readFile(item.path)).digest('hex'),item.sha256,item.path);
const original=execFileSync('git',['show',`${baseline.head}:src/lib/instances/ModrinthBrowse.svelte`],{encoding:'utf8'});
const current=await readFile(scoped[0],'utf8');
const scripts=text=>[...text.matchAll(/<script\b[^>]*>[\s\S]*?<\/script>/g)].map(match=>match[0].replaceAll('\r\n','\n'));
assert.deepEqual(scripts(current),scripts(original),'All provider, install and review logic must remain byte-identical');
assert.equal(git('worktree','list','--porcelain').split(/\r?\n\r?\n/).slice(1).join('\n'),baseline.worktrees.split(/\r?\n\r?\n/).slice(1).join('\n'));
assert.equal(git('branch','--show-current'),baseline.branch);
assert.equal(git('diff',baseline.head,'--name-only','--diff-filter=DR'),'');
assert.equal(git('diff','--cached','--name-only','--diff-filter=DR'),'');
execFileSync('git',['diff',baseline.head,'--check']);
const result={startingHead:baseline.head,checkedTracked:baseline.tracked.length,unchangedTracked:baseline.tracked.length-scoped.length,scopedExistingFiles:scoped,protectedFiles:baseline.protected.length,worktrees:7,otherWorktreesUnchanged:true,deletions:0,providerAndInstallScriptUnchanged:true};
if(process.argv[2]!=='--check-only')await writeFile('docs/ui-3-1/preservation.json',JSON.stringify(result,null,2));
console.log('PASS preservation',JSON.stringify(result));
